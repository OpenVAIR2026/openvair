import { expect, test, type Page } from '@playwright/test'
import type { ModelCatalogEntry, ModelPrice, PriceSyncChange, Channel } from '../src/lib/api'

const entry = (pattern: string, price: number | null = null): ModelCatalogEntry => ({ id: pattern, pattern, label: pattern, enabled: true, provider: 'Fixture', protocols: ['openai'], input_per_1m: price, output_per_1m: price == null ? null : 8, cached_read_per_1m: price == null ? null : 0.5, price_source: null, created_at: '', updated_at: '' })
const reference = (pattern: string): ModelPrice => ({ pattern, label: pattern, input_per_1m: 2, output_per_1m: 8, cached_read_per_1m: 0.5, synced_from: 'openrouter' })

async function fixtures(page: Page) {
  const channel: Channel = { id: 'channel-one', name: '主渠道', protocol: 'openai', base_url: 'https://api.example.invalid', enabled: true, priority: 10, health_status: 'healthy', health_error: null, health_checked_at: null, test_model: 'gpt-one', models: ['gpt-*'], model_mapping: {}, model_mode: 'allowlist', model_count: 2, known_models: ['gpt-one', 'gpt-two'], discovered_models: [], models_synced_at: null, created_at: new Date().toISOString() }
  const state = { catalog: [entry('gpt-one', 2), entry('gpt-two'), entry('gpt-*')], channel, keys: [] as Record<string, unknown>[], catalogPosts: [] as Record<string, unknown>[], catalogPatches: [] as Record<string, unknown>[], keyPosts: [] as Record<string, unknown>[], channelPatches: [] as Record<string, unknown>[], channelPosts: [] as Record<string, unknown>[], draftChecks: [] as Record<string, unknown>[], draftModels: [] as Record<string, unknown>[], draftHealthy: true, channelCheckNeedsKey: false, channelChecks: 0, synced: [] as string[], syncGate: null as Promise<void> | null, failSync: false, failSave: false, failDiscovery: false, referencePrices: [reference('gpt-one'), reference('gpt-two')], syncBatches: [] as PriceSyncChange[][], failPreview: false, failBatch: false }
  await page.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname
    const method = route.request().method()
    const send = (data: unknown, status = 200) => route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(data) })
    if (path === '/api/me') return send({ user_id: 'demo', email: 'demo@example.invalid', account_id: 'account', is_super_admin: true })
    if (path === '/api/account') return send({ id: 'account', name: '模型管理验证', api_key_prefix: 'demo' })
    if (path === '/api/model-catalog') {
      if (method === 'POST') {
        const input = route.request().postDataJSON(); state.catalogPosts.push(input)
        if (state.failSave) return send({ error: { message: '模拟保存失败' } }, 503)
        state.catalog.push({ ...entry(input.pattern), ...input, input_per_1m: input.price?.input_per_1m ?? null, output_per_1m: input.price?.output_per_1m ?? null, cached_read_per_1m: input.price?.cached_read_per_1m ?? null })
      }
      return send(state.catalog)
    }
    if (path.startsWith('/api/model-catalog/')) {
      const id = decodeURIComponent(path.split('/').at(-1)!)
      if (method === 'DELETE') state.catalog = state.catalog.filter(item => item.id !== id)
      if (method === 'PATCH') {
        const input = route.request().postDataJSON(); state.catalogPatches.push(input)
        if (input.only_unpriced && state.catalog.find(item => item.id === id)?.input_per_1m != null) return send({ error: { message: '模型已修改，请刷新后重试' } }, 409)
        state.catalog = state.catalog.map(item => item.id === id ? { ...item, ...input, ...(input.price ? { input_per_1m: input.price.input_per_1m, output_per_1m: input.price.output_per_1m, cached_read_per_1m: input.price.cached_read_per_1m } : {}) } : item)
      }
      return send(state.catalog.find(item => item.id === id) ?? {})
    }
    if (path === '/api/platform/model-pricing/unpriced') return state.failDiscovery ? send({ error: { message: '发现暂不可用' } }, 503) : send({ since: new Date().toISOString(), models: ['new-model', 'new-model-mini'].filter(model => !state.catalog.some(item => item.pattern === model && item.input_per_1m != null)).map(model => ({ model, requests: 5, last_seen_at: new Date().toISOString() })) })
    if (path === '/api/platform/model-pricing/catalog') return send([reference('new-model')])
    if (path === '/api/platform/model-pricing/sync-preview') {
      if (state.failPreview) return send({ error: { message: '参考价获取失败，请稍后重试' } }, 503)
      return send(state.catalog.flatMap(item => {
        const ref = state.referencePrices.find(price => price.pattern === item.pattern)
        if (!ref || item.pattern.endsWith('*') || item.input_per_1m === ref.input_per_1m && item.output_per_1m === ref.output_per_1m && item.cached_read_per_1m === ref.cached_read_per_1m) return []
        return [{ id: item.id, pattern: item.pattern, label: item.label, updated_at: item.updated_at, current: item.input_per_1m == null ? null : { input_per_1m: item.input_per_1m, output_per_1m: item.output_per_1m, cached_read_per_1m: item.cached_read_per_1m }, reference: { input_per_1m: ref.input_per_1m, output_per_1m: ref.output_per_1m, cached_read_per_1m: ref.cached_read_per_1m } }]
      }))
    }
    if (path === '/api/platform/model-pricing/sync') {
      const changes: PriceSyncChange[] = route.request().postDataJSON().changes
      state.syncBatches.push(changes)
      if (state.syncGate) await state.syncGate
      if (state.failBatch) return send({ error: { message: '模型价格或目录已被修改，请重新获取差异后同步' } }, 409)
      state.catalog = state.catalog.map(item => { const change = changes.find(change => change.id === item.id); return change ? { ...item, ...change.reference, price_source: 'openrouter' } : item })
      return send({ synced: changes.length })
    }
    if (path === '/api/platform/model-pricing/sync-one') {
      const { pattern } = route.request().postDataJSON(); state.synced.push(pattern)
      if (state.syncGate) await state.syncGate
      if (state.failSync) return send({ error: { message: '暂无完整的同名参考价，当前价格未更改，可手动设置' } }, 400)
      state.catalog = state.catalog.map(item => item.pattern === pattern ? { ...item, input_per_1m: 3, output_per_1m: 12, cached_read_per_1m: 0.75, price_source: 'openrouter' } : item)
      return send({ synced: true })
    }
    if (path === '/api/platform/model-pricing' && method === 'POST') { const price = route.request().postDataJSON(); state.catalog.push({ ...entry(price.pattern, price.input_per_1m), output_per_1m: price.output_per_1m, cached_read_per_1m: price.cached_read_per_1m }); return send([]) }
    if (path === '/api/channels') {
      if (method === 'POST') { state.channelPosts.push(route.request().postDataJSON()); return send({ id: 'created-channel' }) }
      return send([state.channel])
    }
    if (path === '/api/channels/preview-check') {
      const input = route.request().postDataJSON(); state.draftChecks.push(input)
      if (state.channelCheckNeedsKey && !input.secret) return send({ error: { message: '未配置可用的上游 API Key，请在表单中填写。' } }, 400)
      return send({ healthy: state.draftHealthy, message: state.draftHealthy ? 'healthy' : 'upstream returned HTTP 401', check_receipt: state.draftHealthy ? 'mock-check-receipt' : null })
    }
    if (path === '/api/channels/preview-models') { state.draftModels.push(route.request().postDataJSON()); return send({ models: ['gpt-discovered'] }) }
    if (/^\/api\/channels\/[^/]+\/check$/.test(path)) {
      state.channelChecks++
      if (state.channelCheckNeedsKey) return send({ error: { message: '未配置可用的上游 API Key，请在编辑渠道中填写。' } }, 400)
      state.channel.health_status = 'healthy'
      return send({ healthy: true, message: 'healthy' })
    }
    if (path === '/api/channels/channel-one/sync-models') { state.channel.discovered_models = ['gpt-discovered']; return send({ models: ['gpt-discovered'] }) }
    if (path === '/api/channels/channel-one' && method === 'PATCH') { const input = route.request().postDataJSON(); state.channelPatches.push(input); const { secret, ...settings } = input; if (secret) state.channelCheckNeedsKey = false; Object.assign(state.channel, settings); return send({}) }
    if (path === '/api/keys') {
      if (method === 'POST') { const input = route.request().postDataJSON(); state.keyPosts.push(input); return send({ id: 'new-key', key: 'test-only-not-a-real-key' }) }
      return send(state.keys)
    }
    if (path === '/api/available-models') return send({ 'gpt-one': 'openai', 'gpt-two': 'openai' })
    return send([])
  })
  return state
}

