#!/bin/sh
# Installs or upgrades OpenVAIR with Docker Compose.
#
#   curl -fsSL https://raw.githubusercontent.com/OpenVAIR2026/openvair/main/install.sh | sh
#
# Environment: OPENVAIR_DIR (default ~/openvair), OPENVAIR_PORT (default 8080),
# OPENVAIR_LAN=yes|no to skip the question, OPENVAIR_REF (default main).
set -eu

REPO=OpenVAIR2026/openvair
REF=${OPENVAIR_REF:-main}
DIR=${OPENVAIR_DIR:-$HOME/openvair}

say() { printf '%s\n' "$*"; }
die() { printf '错误：%s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || die "需要 Docker，请先安装：https://docs.docker.com/engine/install/"
docker compose version >/dev/null 2>&1 || die "需要 Docker Compose v2（docker compose 命令）"
docker info >/dev/null 2>&1 || die "无法连接 Docker。请确认 Docker 已启动，并且当前用户有权限使用（可能需要 sudo 或加入 docker 组）"
if command -v curl >/dev/null 2>&1; then
  fetch() { curl -fsSL "$1"; }
elif command -v wget >/dev/null 2>&1; then
  fetch() { wget -qO- "$1"; }
else
  die "需要 curl 或 wget"
fi

mkdir -p "$DIR"
cd "$DIR"
say "安装目录：$DIR"

fetch "https://raw.githubusercontent.com/$REPO/$REF/docker-compose.yml" > docker-compose.yml.new \
  || die "下载 docker-compose.yml 失败"
mv docker-compose.yml.new docker-compose.yml

if [ -f .env ]; then
  say "保留已有的 .env，按其中的设置升级。"
else
  port=${OPENVAIR_PORT:-8080}
  lan=${OPENVAIR_LAN:-}
  # Piped into sh, stdin is the script itself; ask on the terminal instead.
  if [ -z "$lan" ] && { exec 3</dev/tty; } 2>/dev/null; then
    printf '是否允许局域网内的其他电脑访问（通过 http://本机IP:%s）？[y/N] ' "$port"
    read -r answer <&3 || answer=
    exec 3<&-
    case "$answer" in [yY]*) lan=yes ;; *) lan=no ;; esac
  fi
  if [ "$lan" = yes ]; then
    # Plain HTTP on a LAN address: a Secure cookie would never be sent back.
    bind=0.0.0.0 cookie_secure=false
  else
    bind=127.0.0.1 cookie_secure=true
  fi
  umask 077
  cat > .env <<EOF
# Generated by install.sh. The database password and MASTER_KEY are created on
# first start and kept in the "secrets" Docker volume, not in this file.
OPENVAIR_BIND=$bind
OPENVAIR_PORT=$port
COOKIE_SECURE=$cookie_secure
EOF
  umask 022
fi

say "正在下载镜像…"
docker compose pull --ignore-buildable 2>/dev/null || docker compose pull \
  || die "拉取镜像失败。请检查网络；OpenVAIR 镜像在 ghcr.io，Docker Hub 镜像加速对它无效，国内服务器的处理办法见 https://github.com/$REPO/blob/main/docs/self-hosting.md"
docker compose up -d --no-build || die "启动失败，查看日志：cd $DIR && docker compose logs"

port=$(sed -n 's/^OPENVAIR_PORT=//p' .env | tail -1)
port=${port:-8080}
say "等待服务就绪…"
i=0
until docker compose exec -T openvair curl -fsS http://127.0.0.1:8080/healthz >/dev/null 2>&1; do
  i=$((i + 1))
  [ "$i" -lt 60 ] || die "服务 2 分钟内没有就绪，查看日志：cd $DIR && docker compose logs openvair"
  sleep 2
done

say ""
say "OpenVAIR 已启动：http://localhost:$port"
if grep -q '^OPENVAIR_BIND=0.0.0.0' .env; then
  ip=$( (hostname -I 2>/dev/null || ipconfig getifaddr en0 2>/dev/null) | awk '{print $1}')
  [ -n "$ip" ] && say "局域网地址：http://$ip:$port"
fi
token=$(docker compose logs --no-log-prefix openvair 2>/dev/null \
  | awk '/enter this setup token/ { getline; getline; print $1 }' | tail -1)
if [ -n "$token" ]; then
  say ""
  say "首次使用请打开 /setup 页面，填入初始化令牌并设置管理员："
  say "    $token"
fi
say ""
say "请备份 MASTER_KEY（上游 Key 用它加密，丢失后无法解密）："
say "    cd $DIR && docker compose exec openvair cat /run/openvair/master_key"
